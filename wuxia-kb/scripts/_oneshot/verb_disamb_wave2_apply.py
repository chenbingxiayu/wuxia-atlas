def segment_spans(t: str):
    ms = list(re.finditer(r"\[(\d+)\]", t))
    spans = []
    for i, m in enumerate(ms):
        pn = int(m.group(1))
        start = m.end()
        end = ms[i + 1].start() if i + 1 < len(ms) else len(t)
        spans.append((pn, start, end))
    return spans


