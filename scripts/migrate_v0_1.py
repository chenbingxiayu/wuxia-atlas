"""v0 → v0.1 批量迁移脚本（META-08 类型演化五步流程之第 4 步）

变更内容：
  1. 新类型 [（秘籍/文书）：剑谱/兵书/遗书/制敌之书 加标；
  2. 新动词 ▲（擒控）：捉/擒/点(穴)/点倒/震住 加标；
  3. 新动词 ◇（传艺）：传授/教/指点/相传 加标；
  4. 短名代称升级为标注并挂规范名管道（黄叶/红云/贞乾/珊瑚/白石/晦明/昌钦/鸣珂）；
  5. 头衔变体统一挂规范名管道（昌钦法师→昌钦大法师，红花鬼母→公孙大娘，@短称→管道）；
  6. 亲属归因结构补标（X的儿子名唤Y 类）。
所有正则均带 lookbehind 守卫，不触碰已有标记内部；替换后必须通过 lint 全量校验。
"""
import re

F001 = "kb/tagged/白发魔女传/001_第一回.tagged.md"
F007 = "kb/tagged/白发魔女传/007_第七回.tagged.md"
F019 = "kb/tagged/白发魔女传/019_第十九回.tagged.md"
F028 = "kb/tagged/白发魔女传/028_第二十八回.tagged.md"


def apply(path, pairs, regexes=()):
    s = open(path, encoding="utf-8").read()
    total = 0
    for old, new in pairs:
        n = s.count(old)
        if n:
            s = s.replace(old, new)
            total += n
    for pat, repl in regexes:
        s, n = re.subn(pat, repl, s)
        total += n
    open(path, "w", encoding="utf-8", newline="").write(s)
    print(f"{path}: {total} 处迁移")


# ---- 001：[剑谱 + ▲震住 + 亲属归因 ----
apply(F001, [
    ("把他们震住", "把他们⟦▲震住⟧"),
    ("儿子名唤〖@卓继贤〗", "〖;儿子〗名唤〖@卓继贤〗"),
    ("孙儿名〖@卓一航〗", "〖;孙儿〗名〖@卓一航〗"),
], regexes=[
    (r"(?<!〖)剑谱(?!〗)", "〖[剑谱〗"),
])

# ---- 007：[剑谱 + 短称/变体管道 + ▲捉 + ◈打伤 + ◇相传 ----
apply(F007, [
    ("〖@贞乾〗", "〖@贞乾|贞乾道人〗"),
    ("〖@黄叶〗", "〖@黄叶|黄叶道人〗"),
    ("〖@红云〗", "〖@红云|红云道人〗"),
    ("又打伤我的女儿", "又⟦◈打伤⟧我的女儿"),
    ("〖@卓一航〗已被捉到〖=延安府〗去了", "〖@卓一航〗已⟦▲捉〗到〖=延安府〗去了"),
    ("内功心得相传，却之不恭", "内功心得⟦◇相传⟧，却之不恭"),
], regexes=[
    (r"(?<!〖)剑谱(?!〗)", "〖[剑谱〗"),
    (r"(?<![@〖])黄叶(?!道人)", "〖@黄叶|黄叶道人〗"),
    (r"(?<![@〖])红云(?!道人)", "〖@红云|红云道人〗"),
    (r"(?<![@〖])贞乾(?!道人|道长)", "〖@贞乾|贞乾道人〗"),
    (r"(?<![@〖铁])珊瑚(?!妹妹)", "〖@珊瑚|铁珊瑚〗"),
    (r"(?<![@〖])白石(?!道人)", "〖@白石|白石道人〗"),
])

# ---- 019：[遗书/制敌之书 + 短称鸣珂 + ▲点倒 ----
apply(F019, [
    ("反手点倒一名卫士", "反手⟦▲点倒⟧一名卫士"),
], regexes=[
    (r"(?<!〖)遗书(?!〗)", "〖[遗书〗"),
    (r"所著的制敌之书", "所著的〖[制敌之书〗"),
    (r"(?<![@〖])鸣珂", "〖@鸣珂|岳鸣珂〗"),
])

# ---- 028：[兵书/遗书 + ◇传艺 + ▲擒/点 + 短称/变体管道 ----
apply(F028, [
    ("一面传授〖@杨云骢〗的技业", "一面⟦◇传授⟧〖@杨云骢〗的技业"),
    ("〖@晦明禅师|岳鸣珂〗教他从〖☆童子功课〗练起", "〖@晦明禅师|岳鸣珂〗⟦◇教⟧他从〖☆童子功课〗练起"),
    ("并叫〖@杨云骢〗教他基本功夫", "并叫〖@杨云骢〗⟦◇教⟧他基本功夫"),
    ("除了亲自教他练〖☆重子功〗之外", "除了亲自⟦◇教⟧他练〖☆重子功〗之外"),
    ("经〖@晦明禅师|岳鸣珂〗⟦◇指点⟧，进益不少", "经〖@晦明禅师|岳鸣珂〗⟦◇指点⟧，进益不少"),
    ("经〖@晦明禅师|岳鸣珂〗指点，进益不少", "经〖@晦明禅师|岳鸣珂〗⟦◇指点⟧，进益不少"),
    ("信手点了他的穴道", "信手⟦▲点⟧了他的穴道"),
    ("可是都给别人擒了。别人敢碰", "可是都给别人⟦▲擒⟧了。别人敢碰"),
    ("而且这四人又给什么人擒了", "而且这四人又给什么人⟦▲擒⟧了"),
    ("乃是晦明的〖;师父〗", "乃是〖@晦明|岳鸣珂〗的〖;师父〗"),
    ("〖@杨涟〗的儿子〖@杨云骢〗", "〖@杨涟〗的〖;儿子〗〖@杨云骢〗"),
    ("〖@昌钦法师〗", "〖@昌钦法师|昌钦大法师〗"),
    ("〖@红花鬼母〗", "〖@红花鬼母|公孙大娘〗"),
], regexes=[
    (r"(?<!〖)兵书(?!〗)", "〖[兵书〗"),
    (r"(?<!〖)遗书(?!〗)", "〖[遗书〗"),
    (r"(?<![@〖])昌钦(?!法师|大法师)", "〖@昌钦|昌钦大法师〗"),
])

print("迁移完成——请立即运行 lint_annotation.py 全量校验")
