new_lines = []
errors = []
for idx, line in enumerate(lines, 1):
    text = line
    ops = OPS.get(idx, [])
    protects = [op[1] for op in ops if op[0] == "P"]
    sent_map = {}
    for i, span in enumerate(protects):
        if span not in text:
            errors.append("L%d 保护串未找到: %r" % (idx, span[:30]))
            continue
        sent = "\x00%d\x00" % i
        sent_map[sent] = span
        text = text.replace(span, sent)
    for op in ops:
        if op[0] != "R":
            continue
        _, old, new, cnt = op
        c = text.count(old)
        if c != cnt:
            errors.append("L%d PhaseA 计数不符 (%d!=%d): %r" % (idx, c, cnt, old))
            continue
        text = text.replace(old, new)
    for old, new in BLANKETS:
        text = text.replace(old, new)
    for sent, span in sent_map.items():
        text = text.replace(sent, span)
    new_lines.append(text)

